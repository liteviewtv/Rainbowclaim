export async function onRequestPost(context) {
  try {
    const body = await context.request.json();
    const walletAddress = String(body?.walletAddress || '').trim();

    if (!/^0x[a-fA-F0-9]{40}$/.test(walletAddress)) {
      return Response.json({ error: 'Invalid Ethereum wallet address.' }, { status: 400 });
    }

    if (!REWARD_ADDRESSES.length) {
      return Response.json({ error: 'No reward addresses configured.' }, { status: 500 });
    }

    const index = Math.floor(Math.random() * REWARD_ADDRESSES.length);
    return Response.json(
      { rewardAddress: REWARD_ADDRESSES[index] },
      { status: 200, headers: { 'Cache-Control': 'no-store' } }
    );
  } catch {
    return Response.json({ error: 'Unable to generate a reward address.' }, { status: 500 });
  }
}
